//! Shard report: renders [`crate::patterns::FileReport`]s as the
//! `FAILURES_SVE_SME.md` fail list (counts + span-annotated samples).

use crate::patterns::{FailKind, FileReport, PatternKind};
use std::fmt::Write as _;

/// How many example spans to list per fail kind in the markdown report.
/// Counts are always exact; only the sample list is capped (the full shards
/// hold tens of thousands of sites — listing all would drown the signal).
pub const SAMPLES_PER_FAIL_KIND: usize = 10;

/// Render the full markdown fail-list document for the given shard reports.
pub fn render_failures_md(
    reports: &[FileReport],
    parse_errors: &[(String, String)],
    peak_rss_kb: Option<u64>,
    generator: &str,
) -> String {
    let mut md = String::new();
    let _ = writeln!(md, "# FAILURES — SVE/SME shards (Lane 32)");
    let _ = writeln!(md);
    let _ = writeln!(
        md,
        "Shard-stage parse of `instrs64_sve.sail` + `instrs64_sme.sail` as \
         independent shards. KEIN Full-Build: constructs this stage cannot \
         lower are listed below with exact spans (`path:line:col-line:col`). \
         Fail counts are *sites*, not definitions."
    );
    let _ = writeln!(md);
    let _ = writeln!(md, "Generated by `{generator}`.");
    let _ = writeln!(md);

    // --- Shard parse summary ------------------------------------------------
    let _ = writeln!(md, "## 1. Shard parse summary");
    let _ = writeln!(md);
    let _ = writeln!(md, "| file | bytes | lines | defs | val | function | other |");
    let _ = writeln!(md, "| --- | ---: | ---: | ---: | ---: | ---: | ---: |");
    let (mut t_bytes, mut t_lines, mut t_defs, mut t_val, mut t_fun, mut t_other) =
        (0u64, 0u64, 0usize, 0usize, 0usize, 0usize);
    for r in reports {
        let _ = writeln!(
            md,
            "| `{}` | {} | {} | {} | {} | {} | {} |",
            r.path, r.bytes, r.lines, r.def_total, r.val_count, r.fun_count, r.other_count
        );
        t_bytes += r.bytes as u64;
        t_lines += r.lines;
        t_defs += r.def_total;
        t_val += r.val_count;
        t_fun += r.fun_count;
        t_other += r.other_count;
    }
    let _ = writeln!(
        md,
        "| **total** | **{t_bytes}** | **{t_lines}** | **{t_defs}** | **{t_val}** | **{t_fun}** | **{t_other}** |"
    );
    let _ = writeln!(md);
    if parse_errors.is_empty() {
        let _ = writeln!(md, "Parse errors: **none** — both shards split cleanly into");
        let _ = writeln!(md, "`file_start`/`file_end`-wrapped definition lists.");
    } else {
        let _ = writeln!(md, "Parse errors: **{}**", parse_errors.len());
        for (path, err) in parse_errors {
            let _ = writeln!(md, "- `{path}`: {err}");
        }
    }
    let _ = writeln!(md);
    match peak_rss_kb {
        Some(kb) => {
            let _ = writeln!(
                md,
                "Peak RSS during parse + analyze (both shards, parallel): **{kb} KiB** \
                 (`VmHWM`). Per-definition processing — bodies are sliced, never copied."
            );
        }
        None => {
            let _ = writeln!(
                md,
                "Peak RSS: n/a (non-Linux host). Design is per-definition streaming: \
                 bodies are sliced via spans, never copied."
            );
        }
    }
    let _ = writeln!(md);

    // --- Pattern catalog -----------------------------------------------------
    let _ = writeln!(md, "## 2. Vector-pattern / loop catalog");
    let _ = writeln!(md);
    let _ = writeln!(md, "| pattern | sve | sme | total |");
    let _ = writeln!(md, "| --- | ---: | ---: | ---: |");
    for kind in PatternKind::all() {
        let counts: Vec<u64> = reports.iter().map(|r| r.pattern_count(*kind)).collect();
        let total: u64 = counts.iter().sum();
        if total == 0 {
            continue;
        }
        let cols: Vec<String> = counts.iter().map(|c| c.to_string()).collect();
        let _ = writeln!(md, "| `{}` | {} | {} |", kind.as_str(), cols.join(" | "), total);
    }
    let _ = writeln!(md);

    // --- Fail summary ---------------------------------------------------------
    let _ = writeln!(md, "## 3. Fail summary (non-lowerable sites)");
    let _ = writeln!(md);
    let _ = writeln!(md, "| fail kind | sve | sme | total | owning lane |");
    let _ = writeln!(md, "| --- | ---: | ---: | ---: | --- |");
    for kind in FailKind::all() {
        let counts: Vec<u64> = reports.iter().map(|r| r.fail_count(*kind)).collect();
        let total: u64 = counts.iter().sum();
        if total == 0 {
            continue;
        }
        let cols: Vec<String> = counts.iter().map(|c| c.to_string()).collect();
        let _ = writeln!(
            md,
            "| `{}` | {} | {} | Lane {} |",
            kind.as_str(),
            cols.join(" | "),
            total,
            kind.lane()
        );
    }
    let grand: u64 = reports.iter().map(|r| r.total_fails()).sum();
    let _ = writeln!(md);
    let _ = writeln!(md, "Total fail sites: **{grand}**.");
    let _ = writeln!(md);

    // --- Span-annotated samples ------------------------------------------------
    let _ = writeln!(md, "## 4. Fail samples with spans");
    let _ = writeln!(md);
    let _ = writeln!(
        md,
        "First {SAMPLES_PER_FAIL_KIND} sites per fail kind and shard (source order); \
         counts in §3 are exact."
    );
    let _ = writeln!(md);
    for kind in FailKind::all() {
        let mut shown = false;
        for r in reports {
            let mut n = 0;
            for f in r.fails.iter().filter(|f| f.kind == *kind) {
                if n == 0 {
                    if !shown {
                        let _ = writeln!(md, "### `{}` → Lane {}", kind.as_str(), kind.lane());
                        let _ = writeln!(md);
                        shown = true;
                    }
                    let _ = writeln!(md, "Shard `{}`:", r.path);
                }
                if n >= SAMPLES_PER_FAIL_KIND {
                    break;
                }
                let _ = writeln!(md, "- `{}` in `{}` — {}", f.span, f.def_name, f.detail);
                n += 1;
            }
            if n > 0 {
                let total = r.fail_count(*kind);
                if total > n as u64 {
                    let _ = writeln!(md, "  (… {} more sites of this kind in this shard)", total - n as u64);
                }
                let _ = writeln!(md);
            }
        }
    }

    // --- Regeneration ----------------------------------------------------------
    let _ = writeln!(md, "## 5. Regeneration");
    let _ = writeln!(md);
    let _ = writeln!(md, "```sh");
    let _ = writeln!(
        md,
        "cargo run --example shard_sve_sme -- <path-to>/instrs64_sve.sail <path-to>/instrs64_sme.sail > FAILURES_SVE_SME.md"
    );
    let _ = writeln!(md, "```");
    md
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::patterns::analyze_file;

    const MINI: &str = "val v : (int) -> unit\n\nfunction v (x) = {\n    throw(Error_Undefined())\n}\n";

    #[test]
    fn renders_counts_and_spans() {
        let r = analyze_file("mini.sail", MINI).unwrap();
        let md = render_failures_md(std::slice::from_ref(&r), &[], None, "test");
        assert!(md.contains("| `exception_semantics` | 1 | 1 | Lane 28 (early-return-except) |"));
        assert!(md.contains("mini.sail:4:5-4:10"));
        assert!(md.contains("Total fail sites: **1**."));
    }
}
